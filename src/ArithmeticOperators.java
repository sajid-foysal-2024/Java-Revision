// ==================== ব্যাখ্যা (Description) ====================
// 1. Arithmetic operator দিয়ে সাধারণ গাণিতিক কাজ করা হয়।
//
//    চিহ্ন   নাম              কাজ
//    ----   ---------------  -----------------------------
//     +     Addition         দুটো মান যোগ করে
//     -     Subtraction      এক মান থেকে আরেক মান বিয়োগ করে
//     *     Multiplication   দুটো মান গুণ করে
//     /     Division         এক মানকে আরেক মান দিয়ে ভাগ করে
//     %     Modulus          ভাগশেষ (remainder) দেয়
//     ++    Increment        ভ্যারিয়েবলের মান 1 বাড়ায়
//     --    Decrement        ভ্যারিয়েবলের মান 1 কমায়
//
// 2. Modulus (%) বোঝার উপায়:
//    10 % 3 মানে 10 কে 3 দিয়ে ভাগ করলে ভাগশেষ কত।
//    10 = 3 x 3 + 1, তাই ভাগশেষ 1।
//
// 3. গুরুত্বপূর্ণ নোট (পূর্ণ সংখ্যার ভাগ):
//    দুটো int ভাগ করলে ফলাফলও int হয়, দশমিক অংশ বাদ পড়ে যায়।
//    যেমন: 10 / 3 এর ফলাফল 3 (3.33 নয়)।
//    দশমিক ফলাফল চাইলে double মান ব্যবহার করতে হবে, যেমন 10.0 / 3.0
// ================================================================

public class ArithmeticOperators {
    public static void main(String[] args) {

        // ==================== উদাহরণ ১: সব অপারেটর একসাথে ====================
        int x = 10;
        int y = 3;

        System.out.println(x + y); // যোগ: 10 + 3 = 13
        System.out.println(x - y); // বিয়োগ: 10 - 3 = 7
        System.out.println(x * y); // গুণ: 10 * 3 = 30
        System.out.println(x / y); // ভাগ: 10 / 3 = 3 (পূর্ণ সংখ্যার ভাগ, দশমিক বাদ)
        System.out.println(x % y); // ভাগশেষ: 10 % 3 = 1

        // ==================== উদাহরণ ২: Increment ও Decrement ====================
        int z = 5;

        ++z; // z এর মান 1 বাড়লো: 5 -> 6
        System.out.println(z); // আউটপুট: 6

        --z; // z এর মান 1 কমলো: 6 -> 5
        System.out.println(z); // আউটপুট: 5

        // ==================== উদাহরণ ৩: পূর্ণ সংখ্যা বনাম দশমিক ভাগ ====================

        // দুটোই int, তাই পূর্ণ সংখ্যার ভাগ হয় (দশমিক অংশ বাদ পড়ে)
        int a = 10;
        int b = 3;
        System.out.println(a / b); // আউটপুট: 3

        // দুটোই double, তাই দশমিক সহ নির্ভুল ভাগ হয়
        double c = 10.0d;
        double d = 3.0d;
        System.out.println(c / d); // আউটপুট: 3.3333333333333335
    }
}