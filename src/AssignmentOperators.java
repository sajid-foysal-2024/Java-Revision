// টপিক: Java Assignment Operators
//
// ==================== ব্যাখ্যা (Description) ====================
// 1. Assignment operator দিয়ে ভ্যারিয়েবলে মান বসানো (assign করা) হয়।
//    সবচেয়ে সাধারণ অপারেটর হলো = (যেমন: int x = 10;)
//
// 2. += অপারেটর ভ্যারিয়েবলের বর্তমান মানের সাথে নতুন মান যোগ করে।
//
// 3. সব assignment operator:
//      =    x = 5     মানে  x = 5
//      +=   x += 3    মানে  x = x + 3
//      -=   x -= 3    মানে  x = x - 3
//      *=   x *= 3    মানে  x = x * 3
//      /=   x /= 3    মানে  x = x / 3
//      %=   x %= 3    মানে  x = x % 3
//      &=   x &= 3    মানে  x = x & 3
//      |=   x |= 3    মানে  x = x | 3
//      ^=   x ^= 3    মানে  x = x ^ 3
//      >>=  x >>= 3   মানে  x = x >> 3
//      <<=  x <<= 3   মানে  x = x << 3
//
// 4. বেশিরভাগ assignment operator আসলে লেখা ছোট করার শর্টকাট।
//    যেমন: x += 5 আর x = x + 5 একই কাজ করে, কিন্তু প্রথমটা ছোট
//    এবং পড়তে সহজ।
//
// 5. শেষ পাঁচটা (&=, |=, ^=, >>=, <<=) হলো Bitwise অপারেটরের শর্টকাট।
//    এগুলো সংখ্যার বাইনারি বিট (০ ও ১) নিয়ে কাজ করে:
//      &  (AND) -> দুটো বিট দুটোই 1 হলে ফল 1
//      |  (OR)  -> যেকোনো একটা বিট 1 হলে ফল 1
//      ^  (XOR) -> দুটো বিট আলাদা হলে ফল 1
//      >> -> বিট ডান দিকে সরায় (প্রতি ধাপে মান অর্ধেক হয়)
//      << -> বিট বাঁ দিকে সরায় (প্রতি ধাপে মান দ্বিগুণ হয়)
//    (Bitwise নিয়ে বিস্তারিত পরে শিখবে, এখন শুধু ধারণা রাখলেই চলবে)
// ================================================================

public class AssignmentOperators {
    public static void main(String[] args) {

        // ==================== উদাহরণ ১: = অপারেটর ====================
        int x = 10; // x এ 10 বসানো হলো
        System.out.println("x = " + x); // আউটপুট: x = 10

        // ==================== উদাহরণ ২: += অপারেটর ====================
        x += 5; // x = x + 5, অর্থাৎ 10 + 5 = 15
        System.out.println("x += 5 এর পর x = " + x); // আউটপুট: 15

        // ==================== উদাহরণ ৩: সব অপারেটর একে একে ====================
        // প্রতিবার x কে আবার 10 করে নিয়ে অপারেটরটা প্রয়োগ করা হয়েছে

        x = 5;
        System.out.println("x = 5   -> " + x); // 5

        x = 10;
        x += 3; // 10 + 3
        System.out.println("x += 3  -> " + x); // 13

        x = 10;
        x -= 3; // 10 - 3
        System.out.println("x -= 3  -> " + x); // 7

        x = 10;
        x *= 3; // 10 * 3
        System.out.println("x *= 3  -> " + x); // 30

        x = 10;
        x /= 3; // 10 / 3 (পূর্ণ সংখ্যার ভাগ, দশমিক বাদ)
        System.out.println("x /= 3  -> " + x); // 3

        x = 10;
        x %= 3; // 10 % 3 (ভাগশেষ)
        System.out.println("x %= 3  -> " + x); // 1

        // ---------- Bitwise শর্টকাট ----------
        // 10 এর বাইনারি = 1010, 3 এর বাইনারি = 0011

        x = 10;
        x &= 3; // 1010 & 0011 = 0010 = 2
        System.out.println("x &= 3  -> " + x); // 2

        x = 10;
        x |= 3; // 1010 | 0011 = 1011 = 11
        System.out.println("x |= 3  -> " + x); // 11

        x = 10;
        x ^= 3; // 1010 ^ 0011 = 1001 = 9
        System.out.println("x ^= 3  -> " + x); // 9

        x = 10;
        x >>= 3; // 10 কে 3 ঘর ডানে সরানো: 1010 -> 1 (প্রতি ঘরে অর্ধেক)
        System.out.println("x >>= 3 -> " + x); // 1

        x = 10;
        x <<= 3; // 10 কে 3 ঘর বামে সরানো: 10 * 2 * 2 * 2 = 80
        System.out.println("x <<= 3 -> " + x); // 80

        // ==================== বাস্তব উদাহরণ: সঞ্চয় হিসাব ====================
        int savings = 100;  // শুরুতে সঞ্চয় 100
        savings += 50;      // 50 জমা দেওয়া হলো (savings = savings + 50)
        System.out.println("Total savings: " + savings); // আউটপুট: 150

        // ==================== Exercise ====================
        int score = 10;
        score += 5; // স্কোরের সাথে 5 যোগ
        System.out.println("score = " + score); // আউটপুট: 15
    }
}