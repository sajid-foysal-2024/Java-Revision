// 1. Java র Math ক্লাসে গাণিতিক কাজের জন্য অনেক তৈরি মেথড আছে।
//    ব্যবহার করতে সরাসরি Math.মেথডের_নাম() লিখলেই হয়।
//
// 2. গুরুত্বপূর্ণ মেথড:
//      Math.max(x, y)  -> x ও y এর মধ্যে বড় মান
//      Math.min(x, y)  -> x ও y এর মধ্যে ছোট মান
//      Math.sqrt(x)    -> x এর বর্গমূল
//      Math.abs(x)     -> x এর পরম মান (সবসময় ধনাত্মক)
//      Math.pow(x, y)  -> x এর y ঘাত (x কে y বার গুণ)
//
// 3. Math.pow() নিয়ে নোট:
//    Math.pow(2, 8) মানে 2 x 2 x 2 x 2 x 2 x 2 x 2 x 2 = 256
//    এই মেথড সবসময় double ফেরত দেয়, তাই ফলাফল 256 নয়, 256.0।
//
// 4. গোল করার (Rounding) মেথড:
//      Math.round(x)  -> কাছের পূর্ণ সংখ্যায় গোল করে
//      Math.ceil(x)   -> সবসময় ওপরের দিকে গোল করে (ceil = ছাদ)
//      Math.floor(x)  -> সবসময় নিচের দিকে গোল করে (floor = মেঝে)
//
// 5. র‍্যান্ডম সংখ্যা:
//    Math.random() একটা double দেয়, যা 0.0 থেকে শুরু (অন্তর্ভুক্ত)
//    এবং 1.0 এর আগ পর্যন্ত (1.0 অন্তর্ভুক্ত নয়)।
//    নির্দিষ্ট সীমার পূর্ণ সংখ্যা পেতে সূত্র:
//      (int)(Math.random() * 101)   -> 0 থেকে 100
//    Math.random() double দেয়, তাই পূর্ণ সংখ্যা পেতে (int) দিয়ে cast করতে হয়।
//
// 6. সব Math মেথডের পূর্ণ তালিকা W3Schools এর
//    "Java Math Methods Reference" পেজে পাওয়া যাবে।
//
// 7. নোট: ক্লাসের নাম MathDemo দিয়েছি, Math নয়,
//    কারণ Math নামে Java তে আগে থেকেই একটা ক্লাস আছে।
// ================================================================

public class MathDemo {
    public static void main(String[] args) {

        // ==================== max ও min ====================
        System.out.println(Math.max(5, 10)); // বড় মান। আউটপুট: 10
        System.out.println(Math.min(5, 10)); // ছোট মান। আউটপুট: 5

        // ==================== sqrt (বর্গমূল) ====================
        System.out.println(Math.sqrt(64)); // 8 x 8 = 64, তাই আউটপুট: 8.0

        // ==================== abs (পরম মান) ====================
        System.out.println(Math.abs(-4.7)); // ঋণাত্মক চিহ্ন বাদ। আউটপুট: 4.7

        // ==================== pow (ঘাত) ====================
        System.out.println(Math.pow(2, 8)); // 2 এর 8 ঘাত। আউটপুট: 256.0 (double)

        // ==================== Rounding (গোল করা) ====================
        System.out.println(Math.round(4.6)); // কাছের পূর্ণ সংখ্যা। আউটপুট: 5
        System.out.println(Math.ceil(4.1));  // ওপরের দিকে গোল। আউটপুট: 5.0
        System.out.println(Math.floor(4.9)); // নিচের দিকে গোল। আউটপুট: 4.0

        // ==================== Random (র‍্যান্ডম সংখ্যা) ====================
        // 0.0 থেকে 1.0 এর মধ্যে (1.0 বাদে) একটা double। প্রতিবার আলাদা মান আসবে।
        System.out.println(Math.random());

        // 0 থেকে 100 এর মধ্যে র‍্যান্ডম পূর্ণ সংখ্যা
        // Math.random() * 101 -> 0.0 থেকে 100.999...
        // (int) দিয়ে দশমিক কেটে ফেললে 0 থেকে 100 পর্যন্ত পূর্ণ সংখ্যা হয়
        int randomNum = (int)(Math.random() * 101);
        System.out.println(randomNum);

        // ==================== Exercise ====================
        // সবচেয়ে ছোট মান পেতে min ব্যবহার
        int result = Math.min(5, 10);
        System.out.println(result); // আউটপুট: 5
    }
}