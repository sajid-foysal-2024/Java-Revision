// ফাইলের নাম: MultipleVariables.java
// টপিক: Java Declare Multiple Variables
//
// ==================== ব্যাখ্যা (Description) ====================
// 1. একই টাইপের একাধিক ভ্যারিয়েবল কমা (,) দিয়ে আলাদা করে
//    এক লাইনেই declare করা যায়।
// 2. এক লাইনে লিখলে কোড ছোট হয়, কিন্তু প্রতি লাইনে একটা করে
//    ভ্যারিয়েবল লিখলে অনেক সময় কোড পড়তে সহজ হয়।
// 3. একই মান অনেকগুলো ভ্যারিয়েবলে দিতে চাইলে এক লাইনে
//    x = y = z = 50; এভাবে লেখা যায়।
//    (মান ডান দিক থেকে বাঁ দিকে যায়: z -> y -> x)
// ================================================================

public class MultipleVariables {
    public static void main(String[] args) {

        // ---------- উদাহরণ ১: আলাদা আলাদা লাইনে declare ----------
        // প্রতিটা ভ্যারিয়েবলের জন্য আলাদা লাইন লিখতে হয়েছে
        int a = 5;
        int b = 6;
        int c = 50;
        System.out.println(a + b + c); // 5 + 6 + 50 = 61

        // ---------- উদাহরণ ২: কমা দিয়ে এক লাইনে declare ----------
        // একই টাইপ (int) হলে কমা দিয়ে সব এক লাইনে লেখা যায়
        int x = 5, y = 6, z = 50;
        System.out.println(x + y + z); // আউটপুট: 61

        // ---------- উদাহরণ ৩: একই মান অনেক ভ্যারিয়েবলে ----------
        // আগে তিনটা ভ্যারিয়েবল declare করা হলো (এখনো মান নেই)
        int p, q, r;
        // মান ডান দিক থেকে বাঁ দিকে যায়:
        //   r = 50, তারপর q = r, তারপর p = q
        p = q = r = 50;
        System.out.println(p + q + r); // 50 + 50 + 50 = 150
    }
}