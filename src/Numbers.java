// ==================== ব্যাখ্যা (Description) ====================
// 1. Primitive number টাইপ দুই ভাগে বিভক্ত:
//    (ক) Integer types: পূর্ণ সংখ্যা রাখে (ধনাত্মক বা ঋণাত্মক, দশমিক ছাড়া),
//        যেমন 123 বা -456। টাইপ: byte, short, int, long
//    (খ) Floating point types: দশমিকওয়ালা সংখ্যা রাখে। টাইপ: float, double
//
// 2. অনেক টাইপ থাকলেও সবচেয়ে বেশি ব্যবহৃত হয়:
//    int (পূর্ণ সংখ্যার জন্য) আর double (দশমিক সংখ্যার জন্য)।
//    কোন টাইপ নেবে সেটা নির্ভর করে সংখ্যার মানের ওপর।
//
// 3. Integer টাইপগুলো:
//      byte  -> -128 থেকে 127।
//               মান নিশ্চিতভাবে এই সীমার মধ্যে থাকলে int এর বদলে
//               byte ব্যবহার করে মেমোরি বাঁচানো যায়।
//      short -> -32,768 থেকে 32,767
//      int   -> -2,147,483,648 থেকে 2,147,483,647
//               সংখ্যা রাখার জন্য সাধারণত এটাই পছন্দের টাইপ।
//      long  -> -9,223,372,036,854,775,808 থেকে 9,223,372,036,854,775,807
//               int এ না কুলালে long ব্যবহার করতে হয়।
//               মনে রাখবে: long এর মানের শেষে "L" লিখতে হবে।
// ================================================================

public class Numbers {
    public static void main(String[] args) {

        // ==================== Integer Types ====================

        // ---------- byte ----------
        // সীমা: -128 থেকে 127। মেমোরি বাঁচাতে ছোট মানের জন্য ব্যবহার হয়
        byte myByte = 100;
        System.out.println("byte: " + myByte);

        // ---------- short ----------
        // সীমা: -32768 থেকে 32767
        short myShort = 5000;
        System.out.println("short: " + myShort);

        // ---------- int ----------
        // সীমা: -2147483648 থেকে 2147483647
        // সংখ্যার জন্য সবচেয়ে বেশি ব্যবহৃত (পছন্দের) টাইপ
        int myInt = 100000;
        System.out.println("int: " + myInt);

        // ---------- long ----------
        // int এর সীমা ছাড়িয়ে গেলে long লাগে
        // মনে রাখবে: মানের শেষে L দিতে হবে
        long myLong = 15000000000L;
        System.out.println("long: " + myLong);
    }
}