// ফাইলের নাম: NumbersAndStrings.java
// টপিক: Java Numbers and Strings
//
// ==================== ব্যাখ্যা (Description) ====================
// 1. সতর্কতা: Java তে + অপারেটর দুই কাজে ব্যবহার হয়:
//      - সংখ্যার ক্ষেত্রে: যোগ (addition) হয়
//      - String এর ক্ষেত্রে: জোড়া লাগে (concatenation) হয়
//
// 2. তিনটা ক্ষেত্র:
//      (ক) সংখ্যা + সংখ্যা   -> যোগ হয়, ফলাফল সংখ্যা     (10 + 20 = 30)
//      (খ) String + String   -> জোড়া লাগে, ফলাফল String   ("10" + "20" = "1020")
//      (গ) String + সংখ্যা   -> জোড়া লাগে, ফলাফল String   ("10" + 20 = "1020")
//
// 3. মূল নিয়ম: + এর দুই পাশের যেকোনো একটা String হলে
//    পুরো ফলাফল String হয়ে যায়।
//
// 4. মনে রাখবে: "10" (ডাবল কোটেশনে) হলো লেখা, আর 10 হলো সংখ্যা।
//    দেখতে এক মনে হলেও দুটো আলাদা টাইপ।
// ================================================================

public class NumbersAndStrings {
    public static void main(String[] args) {

        // ==================== ক্ষেত্র ১: সংখ্যা + সংখ্যা ====================
        // দুটোই int, তাই + অপারেটর যোগ করে
        int x1 = 10;
        int y1 = 20;
        int z1 = x1 + y1; // z1 = 30 (একটা সংখ্যা)
        System.out.println(z1); // আউটপুট: 30

        // ==================== ক্ষেত্র ২: String + String ====================
        // দুটোই String (ডাবল কোটেশনে), তাই + অপারেটর জোড়া লাগায়
        String x2 = "10";
        String y2 = "20";
        String z2 = x2 + y2; // z2 = "1020" (একটা String)
        System.out.println(z2); // আউটপুট: 1020

        // ==================== ক্ষেত্র ৩: String + সংখ্যা ====================
        // একটা String, একটা int: ফলাফল String হয়, সংখ্যাটা লেখা হিসেবে জোড়া লাগে
        String x3 = "10";
        int y3 = 20;
        String z3 = x3 + y3; // z3 = "1020" (একটা String)
        System.out.println(z3); // আউটপুট: 1020
    }
}