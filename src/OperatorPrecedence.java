// ==================== ব্যাখ্যা (Description) ====================
// 1. একটা হিসাবে একাধিক অপারেটর থাকলে Java একটা নিয়ম (order of operations)
//    মেনে ঠিক করে কোন অংশ আগে হিসাব হবে।
//    যেমন: গুণ যোগের আগে হয়।
//
// 2. 2 + 3 * 4 এ আগে গুণ হয়, তাই ফলাফল 14।
//    যোগ আগে করতে চাইলে বন্ধনী ( ) দিতে হবে: (2 + 3) * 4 = 20।
//
// 3. অপারেটরের ক্রম (সবচেয়ে বেশি অগ্রাধিকার থেকে সবচেয়ে কম):
//      ১. ( )                  বন্ধনী
//      ২. *  /  %              গুণ, ভাগ, ভাগশেষ
//      ৩. +  -                 যোগ, বিয়োগ
//      ৪. >  <  >=  <=         তুলনা
//      ৫. == !=                সমান / সমান নয়
//      ৬. &&                   Logical AND
//      ৭. ||                   Logical OR
//      ৮. =                    Assignment
//
// 4. একই অগ্রাধিকারের অপারেটর থাকলে Java বাঁ দিক থেকে ডান দিকে হিসাব করে
//    (বন্ধনী না থাকলে)। যেমন: 10 - 2 + 5 এ আগে 10 - 2, তারপর + 5।
//
// 5. টিপ: হিসাব ঠিক ক্রমে হচ্ছে কি না নিশ্চিত হতে সবসময় বন্ধনী ( )
//    ব্যবহার করবে। এতে কোড পড়তেও সহজ হয়।
// ================================================================

public class OperatorPrecedence {
    public static void main(String[] args) {

        // ==================== উদাহরণ ১: গুণ আগে, যোগ পরে ====================
        int result1 = 2 + 3 * 4;    // আগে গুণ: 3 * 4 = 12, তারপর 2 + 12 = 14
        int result2 = (2 + 3) * 4;  // বন্ধনী আগে: 2 + 3 = 5, তারপর 5 * 4 = 20

        System.out.println(result1); // আউটপুট: 14
        System.out.println(result2); // আউটপুট: 20

        // ==================== উদাহরণ ২: বাঁ থেকে ডানে হিসাব ====================
        // যোগ-বিয়োগের অগ্রাধিকার সমান, তাই বাঁ থেকে ডানে হিসাব হয়
        int result3 = 10 - 2 + 5;    // (10 - 2) + 5 = 8 + 5 = 13
        int result4 = 10 - (2 + 5);  // বন্ধনী আগে: 10 - 7 = 3

        System.out.println(result3); // আউটপুট: 13
        System.out.println(result4); // আউটপুট: 3

        // ==================== অতিরিক্ত উদাহরণ (বোঝার জন্য) ====================

        // গুণ ও ভাগের অগ্রাধিকার সমান, তাই বাঁ থেকে ডানে: (10 / 2) * 5
        int result5 = 10 / 2 * 5;    // 5 * 5 = 25
        System.out.println(result5); // আউটপুট: 25

        // তুলনা ও যোগ-গুণ মিশে থাকলে: আগে গুণ, তারপর যোগ, তারপর তুলনা, তারপর &&
        // 5 + 3 > 2 * 3  ->  8 > 6  ->  true
        // 4 != 5         ->  true
        // true && true   ->  true
        boolean check = 5 + 3 > 2 * 3 && 4 != 5;
        System.out.println(check);   // আউটপুট: true

        // && এর অগ্রাধিকার || এর চেয়ে বেশি, তাই && আগে হিসাব হয়
        // true || (false && false)  ->  true || false  ->  true
        boolean logic1 = true || false && false;
        System.out.println(logic1);  // আউটপুট: true

        // বন্ধনী দিয়ে ক্রম বদলে দিলে ফলাফল বদলে যায়
        // (true || false) && false  ->  true && false  ->  false
        boolean logic2 = (true || false) && false;
        System.out.println(logic2);  // আউটপুট: false
    }
}