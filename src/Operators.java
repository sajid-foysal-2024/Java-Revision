//    কোনো কাজ (operation) করা হয়।
//    যেমন: + অপারেটর দিয়ে দুটো মান যোগ করা যায়।
//
// 2. + অপারেটর শুধু দুটো মান যোগ করে না, এগুলোও যোগ করতে পারে:
//      - একটা ভ্যারিয়েবল আর একটা মান
//      - একটা ভ্যারিয়েবল আর আরেকটা ভ্যারিয়েবল
//
// 3. Java অপারেটরকে নিচের গ্রুপগুলোতে ভাগ করেছে:
//      (ক) Arithmetic operators  -> গাণিতিক কাজ (যোগ, বিয়োগ ইত্যাদি)
//      (খ) Assignment operators  -> ভ্যারিয়েবলে মান বসানো
//      (গ) Comparison operators  -> দুটো মান তুলনা করা
//      (ঘ) Logical operators     -> একাধিক শর্ত জুড়ে সিদ্ধান্ত নেওয়া
//      (ঙ) Bitwise operators     -> বিট (০ ও ১) নিয়ে কাজ
//    (প্রতিটা গ্রুপ পরের টপিকগুলোতে আলাদা করে শিখবে)
// ================================================================

public class Operators {
    public static void main(String[] args) {

        // ---------- উদাহরণ ১: দুটো মান যোগ করা ----------
        int x = 100 + 50; // 100 আর 50 যোগ হয়ে 150 হলো
        System.out.println("x = " + x); // আউটপুট: x = 150

        // ---------- উদাহরণ ২: মান আর ভ্যারিয়েবল যোগ করা ----------
        int sum1 = 100 + 50;    // সরাসরি দুটো মান: 150
        int sum2 = sum1 + 250;  // ভ্যারিয়েবল + মান: 150 + 250 = 400
        int sum3 = sum2 + sum2; // ভ্যারিয়েবল + ভ্যারিয়েবল: 400 + 400 = 800

        System.out.println("sum1 = " + sum1); // আউটপুট: sum1 = 150
        System.out.println("sum2 = " + sum2); // আউটপুট: sum2 = 400
        System.out.println("sum3 = " + sum3); // আউটপুট: sum3 = 800
    }
}