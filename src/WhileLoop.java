// ফাইলের নাম: WhileLoop.java
// টপিক: Java While Loop
//
// ==================== ব্যাখ্যা (Description) ====================
// 1. Loop (লুপ) একটা কোড ব্লককে বারবার চালায়, যতক্ষণ একটা শর্ত সত্য (true) থাকে।
//    লুপের সুবিধা: সময় বাঁচায়, ভুল কমায়, কোড পড়তে সহজ করে।
//
// 2. while লুপ শর্ত সত্য থাকা পর্যন্ত কোড ব্লকটা বারবার চালায়।
//
// 3. নিয়ম (syntax):
//      while (condition) {
//        // condition true থাকা পর্যন্ত এই কোড বারবার চলবে
//      }
//
// 4. সতর্কতা: শর্তে ব্যবহার করা ভ্যারিয়েবল বাড়াতে (i++) ভুলবে না।
//    না বাড়ালে শর্ত কখনো মিথ্যা হবে না, আর লুপ কখনো শেষ হবে না
//    (একে infinite loop বলে)।
//
// 5. i হলো একটা counter (গণনার) ভ্যারিয়েবল। সহজ লুপে এটা প্রচলিত নাম,
//    কারণ এটা ছোট, ঐতিহ্যবাহী এবং index বা iterator বোঝায়।
//
// 6. while লুপ দিয়ে উল্টো দিকেও গোনা যায় (countdown)।
//    এক্ষেত্রে মান বাড়ানোর বদলে কমাতে হয় (countdown--)।
// ================================================================

public class WhileLoop {
    public static void main(String[] args) {

        // ==================== উদাহরণ ১: 0 থেকে 4 পর্যন্ত প্রিন্ট ====================
        int i = 0; // counter ভ্যারিয়েবল, শুরুর মান 0

        // i < 5 সত্য থাকা পর্যন্ত লুপ চলবে
        while (i < 5) {
            System.out.println(i); // i এর বর্তমান মান প্রিন্ট
            i++;                   // i এর মান 1 বাড়ানো (না দিলে লুপ কখনো শেষ হতো না)
        }
        // আউটপুট: 0 1 2 3 4 (প্রতিটা আলাদা লাইনে)

        // ==================== উদাহরণ ২: উল্টো গণনা (Countdown) ====================
        int countdown = 3; // 3 থেকে শুরু

        // countdown > 0 সত্য থাকা পর্যন্ত লুপ চলবে
        while (countdown > 0) {
            System.out.println(countdown); // বর্তমান মান প্রিন্ট
            countdown--;                   // মান 1 কমানো: 3 -> 2 -> 1 -> 0
        }
        // countdown 0 হলে শর্ত মিথ্যা হয়, লুপ শেষ

        // এই লাইনটা লুপের বাইরে, তাই লুপ শেষ হওয়ার পর একবারই চলবে
        System.out.println("Happy New Year!!");
    }
}